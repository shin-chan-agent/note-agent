from utils.gemini_client import call_gemini

from config import GEMINI_MODEL_EVALUATION


def quality_check(
    client,
    article,
    past_articles,
    knowledge,
):

    prompt = f"""
以下の記事を総合評価してください。

【記事】
{article}

以下の5項目を評価してください。

①品質
②SEO
③過去記事との重複
④最新情報との整合性
⑤有料記事としての価値

---

【評価時の前提】

・記事生成側で設定された文字数制約を前提として評価してください。
・現在の記事生成では2,000文字以上、最大文字数は設定値で制御しています。
・この文字数制約の中で最高品質になっているかを評価してください。

---

【文字数】

・記事全体の文字数を必ず確認してください。
・記事生成側で設定された最大文字数を超えることを前提とした改善案は提案しないでください。
・文字数そのものを理由に、設定された範囲内の記事を不当に減点しないでください。

---

【品質評価】

次の5項目を20点満点で採点してください。

・読みやすさ
・独自性
・初心者への分かりやすさ
・具体性
・論理性

合計100点満点で評価してください。

情報の正確性を最優先で評価してください。

---

【SEO評価】

100点満点で評価してください。

以下を確認してください。

・タイトルに主要キーワードが自然に含まれているか
・タイトルがクリックしたくなる内容か
・導入文100文字以内に主要キーワードがあるか
・H2・H3にSEOキーワードが自然に含まれているか
・見出しだけ読んでも内容が分かる構成か
・Google検索とnote検索の両方を意識できているか
・キーワードを不自然に詰め込み過ぎていないか

---

【過去記事】

以下には、過去記事のタイトル・テーマ・切り口と、
新しい記事については類似度チェック用の比較テキストが含まれています。

{past_articles}

---

【重複チェック】

今回の記事と過去記事を比較してください。

以下の項目を総合的に確認してください。

・テーマ
・切り口
・タイトル
・記事の中心となる内容
・構成
・H2・H3見出し
・具体例
・解説している手順
・読者が得られる情報
・まとめ

【重要】

タイトルが違うだけでは重複回避とは判断しないでください。

以下の場合は、

DUPLICATE: NG

としてください。

・テーマと切り口がほぼ同じ
・記事の中心となる内容がほぼ同じ
・構成や見出しが大きく類似している
・同じ具体例や手順を中心に解説している
・読者が得られる情報がほぼ同じ
・表現を変更しただけで実質的に同じ記事

一方で、以下の場合は重複とは判断しないでください。

・テーマが同じでも切り口が明確に異なる
・同じサービスを扱っていても目的や読者への価値が異なる
・一部のキーワードや一般的な説明が共通しているだけ
・同じサービスの料金や基本機能など、避けることが難しい共通情報のみ
・読者が別の記事として読む価値が十分にある

単なるキーワードの一致だけでNGにしないでください。

重複判定は、
「記事全体として読者に提供する価値がどの程度重なっているか」
を基準にしてください。

問題がなければ、

DUPLICATE: OK

問題がある場合は、

DUPLICATE: NG

としてください。

DUPLICATE: NGの場合は、
どの過去記事とどの部分が重複しているのかを
【必須】の改善点へ具体的に記載してください。

---

【AI知識DB】

{knowledge}

---

【AI知識DBチェック】

上記のAI知識DBと記事を比較してください。

以下について誤りや古い情報がないか確認してください。

・料金
・プラン
・対応モデル
・機能
・仕様
・注意点

問題がなければ、

LATEST: OK

問題がある場合は、

LATEST: NG

としてください。

LATEST: NGの場合は、
どの情報が誤っている、または古いのか、
どのように修正すべきかを
【必須】の改善点へ具体的に記載してください。

---

【有料記事としての価値】

この記事が実際に有料noteとして販売できる内容になっているか評価してください。

以下を総合的に確認してください。

・有料部分に具体的な実践価値がある
・無料部分と有料部分の役割が明確に分かれている
・無料部分だけで記事全体の実践価値を完全に得られない
・有料部分だけを読んでも実践できる
・読者が実際に行動できる具体的な内容がある
・テーマと切り口に適した具体情報がある
・必要に応じて手順、テンプレート、プロンプト、比較、判断基準、失敗回避などが含まれている
・単なる一般論や情報の寄せ集めになっていない
・購入後に再利用できる情報がある
・読者が購入する合理的な理由がある

以下の場合は、

PAID_VALUE: NG

としてください。

・有料部分が一般論中心
・無料部分と有料部分の差が小さい
・有料部分に具体的な実践方法が不足している
・読者が実際に行動するための情報が不足している
・テーマや切り口に対して有料部分の内容が薄い
・単なる情報紹介で、購入する合理的な理由が弱い

以下の場合は、

PAID_VALUE: OK

としてください。

・有料部分に十分な実践価値がある
・無料部分との差別化が明確
・読者が実際に行動できる
・テーマと切り口に適した具体的な情報がある
・購入後も再利用できる情報がある

PAID_VALUE: NGの場合は、
何が不足しているのか、
どう改善すべきなのかを
【必須】の改善点へ具体的に記載してください。

単に「有料部分を充実させる」のような
抽象的な改善指示は禁止します。

---

【出力形式】

必ず以下の形式で出力してください。

SCORE:◯◯
SEO:◯◯
DUPLICATE: OK または NG
LATEST: OK または NG
PAID_VALUE: OK または NG

改善点

【必須】
・○○

【推奨】
・○○

この見出し名・順番を変更しないでください。

品質・SEO・重複・最新情報・有料記事価値の
すべてに問題がない場合のみ、

「改善点なし」

と出力してください。

---

【必須に記載する内容】

以下の場合のみ記載してください。

・事実誤認
・最新情報との不一致
・SEO上重大な問題
・記事構成上の重大な問題
・重複の問題
・有料記事として重大な価値不足
・読者の理解を大きく妨げる問題

DUPLICATE: NGの場合は、
必ず重複している過去記事と、
具体的にどの内容が重複しているのかを記載してください。

PAID_VALUE: NGの場合は、
不足している具体的な内容と、
追加・修正すべき具体的な内容を記載してください。

---

【推奨に記載する内容】

・具体例を追加すると良い
・比較表があると良い
・補足するとより理解しやすい
・表現をより自然にできる

---

【重要な判定ルール】

・記事生成側の文字数制約を超えることを前提とした改善案は禁止です。
・単なるキーワード一致だけでDUPLICATE:NGにしないでください。
・同じテーマでも、切り口・目的・具体的な内容が異なる場合はOKとしてください。
・重複しているか判断できない場合は、推測でNGにしないでください。
・明確に内容が重複している場合のみNGとしてください。
・有料部分に具体的な価値がある場合は、単に無料部分より情報量が多いという理由だけでNGにしないでください。
・テーマと切り口に必要な実践情報が提供されていれば、テンプレートやプロンプトなどを無理に追加する必要はありません。

記事は2,000〜5,000文字程度を前提としてください。

その文字数を超えることを前提とした改善案は提案しないでください。

出力は上記の形式のみとし、
前置き・解説・補足は出力しないでください。
"""

    response = call_gemini(
        client,
        model=GEMINI_MODEL_EVALUATION,
        contents=prompt,
    )

    return response.text