from utils.gemini_client import call_gemini

from config import GEMINI_MODEL_EVALUATION


def quality_check(
    client,
    article,
    past_articles,
    knowledge,
):

    prompt = f"""

以下の記事を総合評価してください。

【記事】
{article}

以下の4項目を評価してください。

①品質
②SEO
③過去記事との重複
④最新情報との整合性


---

【評価時の前提】

この記事は無料の初心者向けnote記事です。

記事生成では、
「テーマ」と「切り口」を明確に設定しています。

評価では、
記事単体の品質だけでなく、

・テーマが記事全体の中心になっているか
・切り口が記事全体に反映されているか
・テーマと切り口の組み合わせに意味があるか
・初心者にとって理解しやすいか
・読者が実際に行動できる内容になっているか

も確認してください。

記事生成側で設定された文字数制約を前提として評価してください。

現在の記事生成では、
2,000文字以上、
最大文字数は設定値で制御しています。

この文字数制約の範囲内で、
情報量・読みやすさ・具体性のバランスが取れているかを評価してください。


---

【文字数】

・記事全体の文字数を必ず確認してください。
・記事生成側で設定された最大文字数を超えることを前提とした改善案は提案しないでください。
・2,000文字以上であれば、文字数そのものを理由に不当に減点しないでください。
・文字数を増やすこと自体を目的とした改善案は禁止します。


---

【品質評価】

次の5項目を20点満点で採点してください。

・読みやすさ
・独自性
・初心者への分かりやすさ
・具体性
・論理性

合計100点満点で評価してください。

特に以下を重視してください。

・テーマと切り口が一貫しているか
・一般論だけで終わっていないか
・初心者が内容を理解できるか
・具体例や具体的な行動が含まれているか
・記事全体の論理が自然につながっているか

情報の正確性を最優先で評価してください。


---

【SEO評価】

100点満点で評価してください。

以下を確認してください。

・タイトルにテーマに適した主要キーワードが自然に含まれているか
・タイトルが記事内容を正確に表しているか
・タイトルがnoteの記事一覧や検索結果で内容を理解しやすいか
・導入文の早い段階に主要キーワードが自然に含まれているか
・H2・H3にSEOキーワードが自然に含まれているか
・見出しだけ読んでも記事内容が把握できる構成か
・Google検索とnote検索の両方を意識できているか
・キーワードを不自然に詰め込み過ぎていないか
・テーマと切り口に関係のないキーワードをSEO目的だけで使用していないか

テーマに合わないキーワードを無理に使用していないことも評価してください。


---

【過去記事】

以下には、過去記事のタイトル・テーマ・切り口と、
新しい記事については類似度チェック用の比較テキストが含まれています。

{past_articles}


---

【重複チェック】

今回の記事と過去記事を比較してください。

以下の項目を総合的に確認してください。

・テーマ
・切り口
・タイトル
・記事の中心となる内容
・構成
・H2・H3見出し
・具体例
・解説している手順
・読者が得られる情報
・まとめ

【重要】

タイトルが違うだけでは重複回避とは判断しないでください。

以下の場合は、

DUPLICATE: NG

としてください。

・テーマと切り口がほぼ同じ
・記事の中心となる内容がほぼ同じ
・構成や見出しが大きく類似している
・同じ具体例や手順を中心に解説している
・読者が得られる情報がほぼ同じ
・表現を変更しただけで実質的に同じ記事

一方で、以下の場合は重複とは判断しないでください。

・テーマが同じでも切り口が明確に異なる
・同じサービスを扱っていても目的や読者への価値が異なる
・一部のキーワードや一般的な説明が共通しているだけ
・同じサービスの料金や基本機能など、避けることが難しい共通情報のみ
・読者が別の記事として読む価値が十分にある

単なるキーワードの一致だけでNGにしないでください。

重複判定は、

「記事全体として読者に提供する価値がどの程度重なっているか」

を基準にしてください。

問題がなければ、

DUPLICATE: OK

問題がある場合は、

DUPLICATE: NG

としてください。

DUPLICATE: NGの場合は、
どの過去記事とどの部分が重複しているのかを
【必須】の改善点へ具体的に記載してください。


---

【AI知識DB】

{knowledge}


---

【AI知識DBチェック】

上記のAI知識DBと記事を比較してください。

以下について誤りや古い情報がないか確認してください。

・料金
・プラン
・対応モデル
・機能
・仕様
・注意点
・提供状況

問題がなければ、

LATEST: OK

問題がある場合は、

LATEST: NG

としてください。

LATEST: NGの場合は、
どの情報が誤っている、または古いのか、
どのように修正すべきかを
【必須】の改善点へ具体的に記載してください。


---

【出力形式】

必ず以下の形式で出力してください。

SCORE:◯◯
SEO:◯◯
DUPLICATE: OK または NG
LATEST: OK または NG

改善点

【必須】
・○○

【推奨】
・○○

この見出し名・順番を変更しないでください。

品質・SEO・重複・最新情報のすべてに問題がない場合のみ、

「改善点なし」

と出力してください。


---

【必須に記載する内容】

以下の場合のみ記載してください。

・事実誤認
・最新情報との不一致
・SEO上重大な問題
・記事構成上の重大な問題
・テーマと切り口が記事内容に反映されていない
・初心者にとって理解が大きく困難な問題
・重複の問題
・読者の理解を大きく妨げる問題

DUPLICATE: NGの場合は、
必ず重複している過去記事と、
具体的にどの内容が重複しているのかを記載してください。


---

【推奨に記載する内容】

・具体例を追加するとより分かりやすい
・比較すると理解しやすい
・補足するとより理解しやすい
・表現をより自然にできる
・初心者が実際に試すための説明を少し追加するとよい

ただし、
推奨事項だけを理由に大幅なリライトを要求しないでください。


---

【重要な判定ルール】

・記事生成側の文字数制約を超えることを前提とした改善案は禁止です。
・単なるキーワード一致だけでDUPLICATE: NGにしないでください。
・同じテーマでも、切り口・目的・具体的な内容が異なる場合はOKとしてください。
・重複しているか判断できない場合は、推測でNGにしないでください。
・明確に内容が重複している場合のみNGとしてください。
・テーマと切り口が明確に反映されている記事を評価してください。
・無料記事として初心者に必要な情報が整理されていれば、高度な専門情報がないことを理由に減点しないでください。
・記事を長くすること自体を品質向上と判断しないでください。
・有料記事向けの高度な内容が含まれていないことを理由に減点しないでください。


---

【最終評価】

以下を満たしているか確認してください。

・無料の初心者向け記事として成立している
・テーマが記事全体の中心になっている
・切り口が記事全体に反映されている
・テーマと切り口の組み合わせに意味がある
・具体的な情報が含まれている
・読者が今日から試せる内容がある
・過去記事と実質的に重複していない
・AIサービスに関する情報が最新情報と整合している
・SEO上の重大な問題がない
・記事生成側の文字数制約の範囲内で十分な内容になっている

出力は上記の形式のみとし、
前置き・解説・補足は出力しないでください。
"""

    response = call_gemini(
        client,
        model=GEMINI_MODEL_EVALUATION,
        contents=prompt,
    )

    return response.text