def get_sns_prompt(article):
    return f"""
以下の記事をもとに、X（旧Twitter）、Threads、Instagramの投稿文を作成してください。

【出力形式】

【X】
（ここにX投稿）

【Threads】
（ここにThreads投稿）

【Instagram】
（ここにInstagram投稿）

【Xのルール】

・140文字以内
・1投稿で完結
・最初の1文で興味を引く
・初心者にも分かりやすい文章
・記事の重要なポイントを1〜2個だけ紹介
・記事の内容をすべて説明しない
・「もっと詳しく知りたい」と思える余白を残す
・最後にnote記事への自然なCTAを入れる
・CTAは「詳しくはnoteで解説しています」など、自然な表現にする
・絵文字は0〜2個まで
・ハッシュタグは2個以内
・過度に煽らない
・URLは入れない

【Threadsのルール】

・300〜500文字程度
・Xよりも詳しく内容を伝える
・記事の重要なポイントを2〜3個紹介
・記事全体を単純に要約しない
・読者が「続きも読みたい」と思える内容にする
・冒頭1〜2文で興味を引く
・初心者にも分かりやすい文章
・具体例や実践的なポイントを含める
・適度に改行して読みやすくする
・最後にnote記事への自然なCTAを入れる
・「詳しくはnoteで解説しています」など、自然な表現にする
・URLは入れない
・ハッシュタグは2〜5個程度
・過度に煽らない
・宣伝だけの文章にしない

【Instagramのルール】

・読みやすく改行する
・最初の1〜2行で興味を引く
・記事の内容を要約する
・初心者にも分かりやすくする
・実践に役立つポイントを含める
・最後に保存・いいね・フォローを促す一文を入れる
・note記事への自然な導線を入れる
・ハッシュタグは5〜10個
・URLは入れない
・過度に煽らない

【重要】

3つの投稿文は、それぞれ役割を変えてください。

X：
短く興味を引き、noteを読みたくさせる。

Threads：
記事の一部を詳しく紹介し、noteの内容をもっと読みたくさせる。

Instagram：
記事の要点を分かりやすく整理し、保存・フォローにつなげる。

【記事】

{article}
"""