import json


def get_article_prompt(
    theme,
    angle,
    knowledge,
    past_articles_text,
    current_date,
):

    knowledge_text = json.dumps(
        knowledge,
        ensure_ascii=False,
        indent=2,
    )

    return f"""

noteに投稿する無料記事を1本執筆してください。
記事はMarkdown形式で出力してください。

【記事生成日時】
今日は {current_date} です。

記事内の日時・料金・モデル・サービス開始時期・提供状況などは、
必ずこの日時を基準に判断してください。

未来・過去を取り違えないでください。
提供開始日・終了日・公開日を書く場合は、
記事生成日時との前後関係を確認してください。


【今回の記事テーマ】
テーマ：{theme}
切り口：{angle}

今回の記事は、
「{theme}」をテーマとし、
「{angle}」という切り口から解説してください。

テーマと切り口を記事全体の中心にしてください。

テーマや切り口に直接関係しない話題を無理に追加して、
記事内容を広げないでください。

「テーマ」と「切り口」が自然につながる内容を優先し、
読者が記事を読み終えたときに、
今回のテーマについて具体的な理解を得られる記事にしてください。


【無料記事としての位置付け】

この記事は無料で読める初心者向けの記事です。

以下のような内容を中心にしてください。

・AIで何ができるのか
・どのような場面で使えるのか
・初心者がどう始めればよいのか
・どのAIツールを選べばよいのか
・AIを使う際の基本的な考え方
・よくある失敗や注意点
・具体的な活用例
・実際に試すための基本的な手順

読者が「まず何をすればよいのか」が分かる内容にしてください。

ただし、専門家向けの高度な設計、
複雑な自動化、
大規模な業務システム構築などに深く踏み込む必要はありません。

無料記事として、
「知る」「選ぶ」「始める」「基本的に使う」
ことに価値を置いてください。


【有料記事との差別化】

この記事は無料記事です。

以下のような内容を必要以上に深掘りしないでください。

・高度な業務設計
・複雑な自動化システムの構築
・詳細なワークフロー設計
・高度な品質改善
・専門的な運用設計
・大規模な業務改善
・高度な検証手法
・複雑なプロンプト設計
・専門家向けの細かな最適化

読者が基本を理解し、
自分で最初の一歩を踏み出せるところまでを
無料記事の価値として提供してください。

「無料だから内容が薄い」のではなく、
初心者にとって必要な情報を整理して、
分かりやすく提供することを重視してください。


【過去記事】
{past_articles_text}

上記の過去記事とは、
タイトル・切り口・構成・具体例・説明の順番・まとめなどが
似ない記事を作成してください。

同じ内容を言い換えただけの記事は禁止します。

過去記事に似たテーマが存在する場合でも、
今回の「{angle}」という切り口を明確に変えてください。


【最新情報（AI知識DB）】
{knowledge_text}

上記はAIサービスに関する最新情報です。

記事内でAIサービスの情報を扱う場合は、
この情報を最優先してください。


【AI知識DBの利用ルール】

情報の優先順位は以下の順番で守ってください。

1. AI知識DBに記載された最新情報
2. 記事生成時点で確認できる一般的な情報
3. 既存知識

AI知識DBと既存知識が異なる場合は、
AI知識DBを優先してください。

AI知識DBに存在しない情報は、
推測で補完しないでください。

料金、モデル名、機能、仕様、提供状況など、
変化する可能性がある情報を書く場合は、
AI知識DBの該当情報を確認してください。


【AI知識DBのstatus】

status = available
→ 現在利用可能な情報として扱ってください。

status = deprecated
→ 非推奨の情報です。
現在利用可能な代替情報がある場合は、
そちらを優先してください。

status = discontinued
→ 提供終了・新規利用不可です。
現在利用可能な情報として紹介しないでください。

過去のサービスやモデルについて説明する必要がある場合のみ、
提供終了・非推奨であることが分かるように記述してください。


【AI知識DBを記事内で示さない】

AI知識DBは内部情報源です。

記事本文で、
AI知識DBを参照したことを読者に示してはいけません。

以下の表現は禁止します。

・「AI知識DBでは」
・「AI知識DBによると」
・「AI知識DBに記載されている」
・「AI知識DBの情報によると」
・「データベースによると」
・「登録されている情報では」
・「取得した最新情報によると」
・その他、内部データや情報源の存在を示す表現

AI知識DBの情報は、
記事執筆者が確認した情報として自然に文章へ反映してください。


【対象AIの扱い】

AI知識DBに含まれるAIサービスのうち、
今回のテーマと切り口に関係するものだけを使用してください。

すべてのAIサービスを無理に紹介する必要はありません。

記事内容に必要な場合は、
ChatGPT、Gemini、Claude、Claude Code、
Microsoft Copilot、Perplexity、Gemini Notebook、
Canva、CapCutなどを具体例として使用してください。

ただし、
テーマと切り口に関係のないAIサービスを
数合わせのために紹介してはいけません。

AIサービスを比較する場合は、
記事のテーマと切り口に必要な範囲で比較してください。

特定のAIサービスを不必要に推奨するのではなく、
読者が選択するために必要な違いを分かりやすく説明してください。


【基本ルール】

・確信の持てる情報のみ掲載する
・不明な情報や推測は断定しない
・古い情報を現在の情報として扱わない
・AI知識DBにない情報を勝手に補完しない
・AI特有の不自然な表現を避ける
・「こんにちは」などの挨拶から始めない
・「さあ始めましょう」などの煽る表現を使わない
・「〜ですよね！」などの不自然な読者への呼びかけを避ける
・キャラクター設定や名前を付けない
・同じ表現や言い回しを繰り返さない
・自然で読みやすい日本語を使用する
・初心者にも理解できる説明を心がける
・専門用語を使う場合は簡潔に説明する
・抽象論だけで終わらせない
・必要に応じて具体例を入れる
・読者が実際に試せる内容を含める


【記事構成】

以下の順番を基本として構成してください。

①タイトル
②導入文
③本文
④まとめ
⑤ハッシュタグ

タイトルは必ず
「タイトル：」
から始めてください。

タイトルを省略してはいけません。


【タイトル】

タイトルはSEOだけを目的にせず、
noteの記事一覧やSNSなどで表示されたときの
分かりやすさも重視してください。

検索性・可読性・内容の正確性を両立してください。

・32〜38文字程度を目安とする
・40文字を超えない
・初心者にも内容が伝わる
・テーマと切り口が分かる
・検索されやすい主要キーワードを自然に含める
・重要なキーワードはできるだけ前半に配置する
・本文に存在しない内容をタイトルに入れない
・煽りすぎない
・過度な誇張をしない
・不自然なキーワードの詰め込みをしない
・シンプルで読みやすいタイトルにする

タイトル候補を内部で複数作成し、
その中から最も内容に合った1案だけを出力してください。


【タイトルのキーワード】

テーマと切り口に応じて、
読者が検索すると考えられる自然なキーワードを選んでください。

以下のキーワードを毎回無理に使用してはいけません。

「AI副業」
「ショート動画」
「自動化」
「ロードマップ」
「コスパ」
「時短」

テーマに合う場合のみ使用してください。

テーマと関係のないキーワードを
SEO目的だけでタイトルに入れることは禁止します。


【導入文】

最初の数行で、
読者が抱えている疑問・悩み・知りたいことを示してください。

今回のテーマと切り口が、
導入文だけでも分かるようにしてください。

あいさつは不要です。

導入文は長くしすぎず、
本文を読み進める理由が自然に伝わるようにしてください。


【本文】

本文は2,000〜5,000文字程度を目安としてください。

ただし、
文字数を増やすことを目的にしないでください。

情報量が少ないテーマでは簡潔に、
情報量が多いテーマでは必要十分な説明をしてください。

本文では、
「{theme}」と「{angle}」の両方を一貫して意識してください。

各見出しが単なる一般論にならないようにしてください。

必要に応じて以下を使用してください。

・H2
・H3
・箇条書き
・番号付きリスト
・比較

ただし、
情報を整理するために必要な場合だけ使用してください。

読者がスマートフォンで読みやすい構成を優先してください。


【テーマと切り口の扱い】

今回のテーマ：
「{theme}」

今回の切り口：
「{angle}」

記事全体を通して、
この組み合わせから話題が逸れないようにしてください。

例えば、
「始め方」なら、
初心者が何から始めればよいかを中心に構成してください。

「ツールの選び方」なら、
選ぶ基準や用途ごとの違いを中心にしてください。

「失敗しやすいポイント」なら、
初心者が陥りやすい問題と回避方法を中心にしてください。

「活用アイデア」なら、
具体的な活用場面やアイデアを中心にしてください。

「できること・できないこと」なら、
AIの得意分野と不得意分野を具体的に整理してください。

「比較・レビュー」や「ツール比較」なら、
読者が違いを理解して選択できるようにしてください。

「プロンプトの基本」なら、
初心者が理解できる基本的な考え方と使い方を中心にしてください。

「情報の確認方法」なら、
AIの回答をそのまま信じず確認する基本的な方法を中心にしてください。

「資料・情報の整理方法」なら、
AIを使った情報整理の基本的な考え方を中心にしてください。

上記は構成の参考であり、
記事内容に応じて自然に調整してください。


【具体例】

可能な場合は、
読者がイメージしやすい具体例を入れてください。

ただし、
実在の人物・企業・収益額・実績などを
根拠なく作ってはいけません。

架空の例を使用する場合は、
架空の例であることが分かるようにしてください。

「自分が実際に経験した」ような
架空の体験談を作成してはいけません。


【実践ポイント】

記事の最後までに、
読者が今日から試せる具体的な行動を
1つ以上提示してください。

ただし、
今回のテーマと切り口に関係する行動にしてください。


【まとめ】

まとめでは、
記事の重要なポイントを3〜5項目程度に整理してください。

単に本文を繰り返すだけではなく、
読者が今回の記事から何を理解し、
次に何をすればよいのかが分かるようにしてください。

今回の記事のテーマと切り口から自然に締めくくってください。

特定の固定記事や別の記事への誘導は不要です。


【ハッシュタグ】

記事内容に適したハッシュタグを
5〜10個作成してください。

テーマと記事内容に関係するものを選んでください。

半角スペースを1つ挟んで横並びで出力してください。


【禁止事項】

・AI知識DBの存在を記事内で示す
・根拠のない情報を断定する
・古い情報を現在の情報として紹介する
・存在しない機能や料金を作る
・架空の実績を作る
・架空の体験談を作る
・テーマと無関係なAIサービスを無理に紹介する
・テーマと切り口を無視して一般論だけを書く
・同じ内容を過去記事の言い換えとして書く
・過度な煽り
・不必要な広告的表現
・固定記事への誘導
・画像生成用のメタデータ
・記事以外の説明文


【記事セルフチェック】

記事を出力する前に、以下をすべて確認してください。

《テーマ・切り口》
□ テーマ「{theme}」が記事全体の中心になっている
□ 切り口「{angle}」が記事全体に反映されている
□ テーマと切り口の組み合わせに意味のある記事になっている

《最新情報》
□ AI知識DBの最新情報を優先している
□ 古い料金・プラン・モデル・機能・仕様を書いていない
□ 推測や未確認情報を断定していない
□ discontinuedのサービスやモデルを現在利用可能として扱っていない

《AIサービス》
□ テーマと切り口に関係するAIサービスだけを使用している
□ AIサービスを数合わせで紹介していない
□ 必要な場合のみサービス間の違いを説明している

《無料記事》
□ 初心者が理解しやすい
□ 「知る・選ぶ・始める・基本的に使う」に価値を置いている
□ 高度な専門領域に不必要に踏み込んでいない
□ 無料記事として十分な情報量がある

《オリジナリティ》
□ 過去記事とタイトルが似ていない
□ 過去記事と切り口が似ていない
□ 過去記事と構成が似すぎていない
□ 過去記事と具体例が似ていない
□ 同じ内容を言い換えただけの記事になっていない

《読みやすさ》
□ 初心者にも理解できる
□ スマートフォンで読みやすい
□ 見出しが内容を正確に表している
□ 同じ表現を繰り返していない
□ 必要に応じて箇条書きや番号付きリストを使用している

《SEO》
□ タイトルが32〜38文字程度
□ タイトルが40文字以内
□ テーマに合った検索キーワードを自然に含んでいる
□ 不自然なキーワード詰め込みをしていない

《実用性》
□ 具体例または具体的な使い方を含んでいる
□ 読者が今日から試せる行動を1つ以上提示している
□ 記事を読んだ後に次の行動が分かる

《構成》
□ 「タイトル：」から開始している
□ 導入文がある
□ 本文にH2・H3見出しを使用している
□ まとめがある
□ ハッシュタグを5個以上出力している
□ 固定記事への誘導を入れていない
□ 画像生成用メタデータを出力していない

【最終確認】

記事を書き終えた後、
上記のセルフチェックを内部で実施してください。

条件を満たしていない項目がある場合は、
記事全体を修正してから再度確認してください。

最終的に、
そのままnoteへ投稿できる完成版の記事だけを出力してください。

セルフチェックの内容や判断結果は出力しないでください。
"""