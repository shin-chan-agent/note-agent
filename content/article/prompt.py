import json


def get_article_prompt(
    theme,
    angle,
    knowledge,
    past_articles_text,
    current_date,
):

    knowledge_text = json.dumps(
        knowledge,
        ensure_ascii=False,
        indent=2,
    )

    return f"""

noteで販売する有料記事を1本執筆してください。
記事はMarkdown形式で出力してください。

【記事生成日時】
今日は {current_date} です。

記事内の日時・料金・モデル・サービス開始時期・提供状況などは、必ずこの日時を基準に判断してください。

未来・過去を取り違えないでください。
提供開始日・終了日・公開日を書く場合は、記事生成日時との前後関係を必ず確認してください。


【過去記事タイトル】
{past_articles_text}

上記の過去記事とは、
タイトル・テーマ・切り口・構成・具体例・結論が似ない記事を作成してください。

過去記事の内容を単に言い換えただけの記事は禁止します。


【今回の記事テーマ】
テーマ：{theme}

【今回の記事の切り口】
切り口：{angle}

この記事は、
上記のテーマと切り口の組み合わせを中心に構成してください。

テーマと切り口から自然に導けない内容を無理に追加しないでください。


【記事の基本方針】

この記事は「有料note」として販売することを前提にしてください。

単なる情報紹介や一般論ではなく、読者が記事を読んだ後に実際の行動へ移せる内容を提供してください。

特に有料部分では、以下のような「購入後に実際に使える情報」を可能な限り含めてください。

・具体的な実践手順
・作業手順
・テンプレート
・プロンプト
・具体例
・比較表
・判断基準
・チェックポイント
・失敗しやすいポイント
・改善方法
・再利用できる考え方
・初心者でも実行できる具体的な方法

ただし、テーマや切り口と関係のない情報を無理に詰め込んではいけません。

情報量を増やすことではなく、「読者が実際に使える情報」を優先してください。


【無料部分と有料部分】

記事は必ず、

①無料部分
②有料部分

の2つに分けてください。

無料部分では、読者が「この記事には自分に必要な情報がある」と判断できるだけの十分な情報を提供してください。

ただし、無料部分だけで記事全体の実践価値を完全に提供してはいけません。

無料部分には以下を含めてください。

・読者が抱えている問題
・なぜその問題が起こるのか
・この記事で分かること
・テーマに関する基本的な考え方
・有料部分で扱う内容の概要
・読者が続きを購入することで得られる具体的なメリット

有料部分では、無料部分で提示した問題を具体的に解決できる内容を提供してください。

有料部分だけを読んでも実践できるよう、必要な手順や具体例を省略しないでください。

「詳しくは有料部分で説明します」のような、内容を実質的に提供しない構成は禁止します。

また、有料部分の内容を無料部分でほぼすべて説明してしまうことも禁止します。


【有料部分の価値】

有料部分には、無料情報を集めただけでは得にくい実践価値を持たせてください。

以下を意識してください。

・何をすればいいか明確
・どの順番で進めるか明確
・どのように判断するか明確
・失敗した場合の対処方法が分かる
・そのまま使えるテンプレートがある
・そのまま使えるプロンプトがある
・具体的な比較や選定基準がある
・読者自身の状況に応用できる

ただし、存在しない実績や成果を作って、記事の価値を高く見せてはいけません。


【AI知識DB】
{knowledge_text}

上記のAI知識DBは、本記事作成における最優先情報源です。

情報の優先順位は以下の順番で必ず守ってください。

1. AI知識DBに記載された最新情報
2. 記事生成時点で確認できる一般的な情報
3. 既存知識

AI知識DBと既存知識が異なる場合、必ずAI知識DBを優先してください。

AI知識DBに存在しない情報は、
推測で補完して断定してはいけません。


【AIツール情報】

AIツールについて記載する場合は、
AI知識DBの以下の情報を確認してください。

・models
・plans
・features
・limitations
・notes
・status
・updated_at
・last_verified

料金、モデル名、機能、仕様、利用制限などは、
確認できた情報だけを記載してください。

statusについては以下を守ってください。

・available
　現在利用可能な情報として使用する。

・deprecated
　非推奨情報として扱い、
　現在利用可能な代替情報がある場合はそちらを優先する。

・discontinued
　提供終了・新規利用不可として扱う。
　現在利用可能なサービスとして紹介・推奨しない。


【AI知識DBの表現ルール】

AI知識DBは記事作成のための内部情報源です。

記事本文では、
AI知識DBを参照したことを読者に示してはいけません。

以下の表現は禁止します。

・「AI知識DBでは」
・「AI知識DBによると」
・「AI知識DBに記載されている」
・「AI知識DBの情報によると」
・「データベースによると」
・「登録されている情報では」
・「取得した最新情報によると」
・その他、内部データや情報源の存在を示す表現

AI知識DBの情報は、
記事執筆者が確認した情報として自然に文章へ反映してください。


【最新情報】

記事内では「現在」「現時点では」などの表現を必要な場合のみ使用してください。

古い料金・プラン・モデル・機能・仕様を、現在利用できる情報として記載しないでください。


【記事の信頼性】

確信の持てる情報のみを掲載してください。

不明な情報や推測を事実として断定しないでください。

存在しない人物・実績・売上・収益・利用者数・体験談などを作り出してはいけません。

「体験した人しか言えない一言」のような架空の体験談も禁止します。

具体例を使用する場合は、架空の実体験ではなく「例として」「仮に」と明示できるケースを使用してください。


【文章ルール】

・自然な日本語で執筆する
・初心者にも理解できる文章にする
・専門用語は簡潔に説明する
・抽象論だけで終わらせない
・同じ表現を繰り返さない
・同じ内容を別の表現で繰り返さない
・不要な前置きを入れない
・過度に煽らない
・誇張表現を避ける
・信頼感を重視する
・「こんにちは」などの挨拶は不要
・キャラクター設定や名前は付けない
・「さあ始めましょう」のようなAI特有の表現を使用しない
・文章の終わりを3回以上連続して同じ語尾にしない


【「ゼロイチ」の使用ルール】

「ゼロイチ」は、「マネタイズにおける最初の1円」という意味で使用する場合のみ許可します。

それ以外の意味では使用しないでください。


【記事構成】

以下の順番を必ず守ってください。

①タイトル
②無料部分
③有料部分
④まとめ
⑤ハッシュタグ

記事の最初は必ず「タイトル：」から開始してください。

タイトルを省略してはいけません。

無料部分と有料部分の境界は、読者に明確に分かるようにしてください。

有料部分の開始位置には、以下のようなMarkdown見出しを使用してください。

## ここから有料部分

有料部分の内容に応じて、その下にH2・H3見出しを適切に配置してください。


【タイトル】

SEOだけでなく、noteの記事一覧やSNSで表示された際の視認性も考慮してください。

検索性・可読性・信頼感を両立したタイトルにしてください。

タイトル候補を内部で5案作成し、その中から最も優れた1案だけを出力してください。

【タイトル文字数】

・32〜38文字程度を推奨
・40文字を超えない
・短すぎるタイトルにしない
・noteの記事一覧で読みやすい長さにする
・内容を正確に表現する
・クリック目的の過剰な煽りをしない

テーマと切り口に応じて、適切なSEOキーワードを自然に使用してください。

以下のキーワードは、記事内容に適している場合のみ使用してください。

・AI副業
・ショート動画
・自動化
・ロードマップ
・コスパ
・時短

これらを無理に入れることは禁止します。


【タイトルSEO】

・主要キーワードを自然に含める
・重要キーワードは可能な範囲で前半に配置する
・タイトルだけで記事内容が分かるようにする
・本文に存在しない内容をタイトルに含めない
・SEOキーワードを詰め込みすぎない


【タイトル可読性】

・初心者にも伝わる表現を使用する
・不要な助詞や冗長な表現を避ける
・一目で内容を理解できるようにする
・途中で改行されても意味が分断されにくい文章にする


【導入】

無料部分の冒頭では、読者が抱えている悩み・問題・疑問から書き始めてください。

あいさつは不要です。

導入文では、この記事を読むことで何が分かるのかを明確にしてください。


【無料部分】

無料部分は、購入前の読者が記事の価値を判断できるだけの内容にしてください。

以下を必要に応じて含めてください。

・問題提起
・原因
・基本的な考え方
・具体的な状況
・簡単な実例
・この記事で分かること
・有料部分で得られる内容

無料部分だけで完結する内容にしない一方、
購入判断に必要な情報は十分に提供してください。


【有料部分】

有料部分では、テーマと切り口に応じた具体的な解決策を提供してください。

記事内容に応じて以下を活用してください。

・手順
・チェックリスト
・テンプレート
・プロンプト
・比較表
・判断基準
・具体例
・失敗例
・改善方法
・作業フロー
・実践時の注意点

ただし、記事テーマと切り口に必要なものだけを使用してください。

例えば「プロンプト」が切り口の場合は、
実際にコピーして使用できるプロンプトを提供してください。

「テンプレート」が切り口の場合は、
読者がそのまま編集して使える形式にしてください。

「比較・選定」の場合は、
単なる特徴紹介ではなく、「どのような人・目的ならどれを選ぶべきか」まで明確にしてください。

「失敗回避」の場合は、
失敗例だけで終わらせず、原因と具体的な回避方法まで説明してください。

「ロードマップ」の場合は、
開始から実践までの順序を明確にしてください。

「実践手順」の場合は、
初心者が上から順番に実行できるレベルまで具体化してください。


【記事の文字数】

記事全体は2,000〜5,000文字程度を目安にしてください。

文字数を増やすことを目的にしてはいけません。

必要な情報を十分に提供しつつ、不要な説明や重複を避けてください。


【SEO】

Google検索とnote内検索の両方を意識してください。

・導入部分に主要キーワードを自然に含める
・H2・H3見出しに関連キーワードを自然に含める
・検索キーワードを過剰に繰り返さない
・検索順位だけを目的にした不自然な文章にしない


【読みやすさ】

スマートフォンで読むことを前提にしてください。

必要に応じて、

・箇条書き
・番号付きリスト
・表
・短い段落

を使用してください。

長い文章を連続させないでください。


【まとめ】

記事の要点を3〜5項目に整理してください。

単なる記事内容の繰り返しではなく、読者が次に何をすればよいのか分かる形で締めてください。

テーマと切り口に応じて、具体的な最初の行動を1つ以上提示してください。


【ハッシュタグ】

記事内容に適したハッシュタグを5〜10個作成してください。

半角スペースを1つ挟んで横並びで出力してください。


【有料記事セルフチェック】

記事を出力する前に、
以下を必ず確認してください。

《記事構成》

□ タイトルが「タイトル：」から始まっている
□ 無料部分がある
□ 有料部分がある
□ まとめがある
□ ハッシュタグが5個以上ある
□ 構成順序が守られている

《有料部分の価値》

□ 有料部分に具体的な実践価値がある
□ 読者が実際に行動できる内容になっている
□ 無料部分との差別化が明確
□ 抽象論だけで終わっていない
□ テーマと切り口に適した具体情報がある
□ 必要に応じてテンプレート・プロンプト・手順・判断基準などを含んでいる
□ 購入後に再利用できる情報がある
□ 有料部分を購入する合理的な理由がある

《テーマ・切り口》

□ 指定されたテーマから逸脱していない
□ 指定された切り口で記事全体を構成している
□ テーマと切り口に関係のない情報を無理に追加していない

《最新情報》

□ AI知識DBの最新情報を最優先している
□ 古い料金・プラン・モデル・機能・仕様を書いていない
□ 推測や未確認情報を断定していない
□ discontinuedのサービスや機能を現在利用可能なものとして紹介していない

《AI知識DB》

□ AI知識DBを情報源として読者に示していない
□ 内部DBや内部情報の存在を記事内に書いていない
□ AI知識DBと既存知識が異なる場合、AI知識DBを優先している

《オリジナリティ》

□ 過去記事とタイトルが似ていない
□ 過去記事と切り口が似ていない
□ 過去記事と構成が似ていない
□ 過去記事の具体例を流用していない
□ 同じ内容を言い換えただけの記事になっていない

《信頼性》

□ 架空の実績を作っていない
□ 架空の収益・売上を作っていない
□ 架空の体験談を作っていない
□ 架空の利用者数や成果を作っていない
□ 不確かな情報を断定していない

《SEO》

□ 主要キーワードを自然に使用している
□ H2・H3見出しにも関連キーワードを自然に使用している
□ キーワードを過剰に繰り返していない

《読みやすさ》

□ 初心者でも理解できる
□ スマートフォンで読みやすい
□ 同じ表現を繰り返していない
□ 不要な説明がない
□ 必要に応じて箇条書き・表などを使用している

《タイトル》

□ 32〜38文字程度
□ 40文字以内
□ 記事内容と一致している
□ 初心者にも内容が伝わる
□ SEOキーワードが自然
□ noteやSNSで表示された際に読みやすい
□ 過度に煽っていない

【最終確認】

記事を書き終えた後、上記の全項目を内部でセルフチェックしてください。

条件を満たしていない項目がある場合は、記事全体を修正してから再度確認してください。

「このまま有料noteとして販売できる品質か」という編集者の視点でも確認してください。

すべての条件を満たした後、完成した記事本文だけを出力してください。

セルフチェックの結果や途中案は出力してはいけません。
"""